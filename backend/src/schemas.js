const { z } = require('zod');

const pin = z.string().regex(/^\d{6}$/, 'PIN must be 6 digits');
const rupees = z.number({ error: 'Amount must be a number' })
  .positive('Amount must be more than zero')
  .refine((v) => Math.abs(v * 100 - Math.round(v * 100)) < 1e-6, 'At most two decimal places');
const dateStr = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Use YYYY-MM-DD');
const name = z.string().trim().min(1, 'Required').max(50).regex(/^[\p{L} .'-]+$/u, 'Letters only');
const optionalName = z.string().trim().max(50).optional().or(z.literal('')).transform((v) => v || undefined);

const login = z.object({
  agentId: z.string().trim().min(3).max(20),
  pin,
  terminalId: z.string().max(60).optional(),
});

const changePin = z.object({ currentPin: pin, newPin: pin });

const cashTxn = z.object({
  customerId: z.string().min(1),
  accountNo: z.string().regex(/^\d{8,16}$/, 'Invalid account number'),
  amount: rupees,
  // Generated by the app for each attempt; resending the same key never creates a second transaction.
  idempotencyKey: z.string().min(8).max(64),
});

const confirmOtp = z.object({ otp: z.string().regex(/^\d{6}$/, 'OTP must be 6 digits') });

const onboarding = z.object({
  firstName: name,
  middleName: optionalName,
  lastName: name,
  gender: z.enum(['male', 'female', 'other']),
  maritalStatus: z.enum(['single', 'married', 'widowed', 'divorced']),
  dobBs: dateStr,
  dobAd: dateStr.refine((d) => {
    const age = (Date.now() - new Date(d).getTime()) / (365.25 * 24 * 3600 * 1000);
    return age >= 16 && age <= 110;
  }, 'Customer must be at least 16 years old'),
  occupation: z.string().trim().min(2).max(60),
  mobile: z.string().regex(/^9[78]\d{8}$/, 'Enter a 10-digit Nepali mobile number starting 97 or 98'),
  citizenshipNo: z.string().trim().regex(/^\d{1,3}(-\d{1,6}){1,4}$/, 'Use the format shown on the certificate, e.g. 27-01-78-04912'),
  citizenshipIssueDateBs: dateStr,
  citizenshipIssueDistrict: z.string().trim().min(2).max(40),
  pan: z.string().regex(/^\d{9}$/, 'PAN must be 9 digits').optional().or(z.literal('')).transform((v) => v || undefined),
  family: z.object({
    fatherName: name,
    motherName: name,
    grandfatherName: name,
    spouseName: optionalName,
  }),
  address: z.object({
    province: z.string().trim().min(2).max(40),
    district: z.string().trim().min(2).max(40),
    municipality: z.string().trim().min(2).max(60),
    ward: z.number().int().min(1).max(35),
    tole: z.string().trim().max(60).optional(),
  }),
  documents: z.object({
    citizenshipFront: z.literal(true, { error: 'Capture the front of the citizenship certificate' }),
    citizenshipBack: z.literal(true, { error: 'Capture the back of the citizenship certificate' }),
    photo: z.literal(true, { error: 'Capture the customer’s photo' }),
  }),
  consent: z.literal(true, { error: 'The customer must agree to the terms' }),
});

const historyQuery = z.object({
  type: z.enum(['deposit', 'withdrawal']).optional(),
  status: z.enum(['confirmed', 'awaiting_otp', 'cancelled', 'failed']).optional(),
  from: z.string().optional(),
  to: z.string().optional(),
  q: z.string().max(60).optional(),
  limit: z.coerce.number().int().min(1).max(200).optional(),
});

const eod = z.object({ countedCash: z.number().min(0).max(10000000), notes: z.string().max(300).optional() });
const rebalance = z.object({ direction: z.enum(['cash_to_bank', 'cash_from_bank']), amount: rupees, notes: z.string().max(300).optional() });
const dispute = z.object({ reason: z.string().trim().min(10, 'Describe the problem in at least 10 characters').max(500) });
const kycDecision = z.object({
  decision: z.enum(['approve', 'reject']),
  reason: z.string().max(300).optional(),
}).refine((v) => v.decision === 'approve' || (v.reason && v.reason.length >= 5), { message: 'Give a reason when rejecting', path: ['reason'] });

module.exports = {
  login, changePin, cashTxn, confirmOtp, onboarding, historyQuery, eod, rebalance, dispute, kycDecision,
};
